//! Puts the application icon into the `.exe` itself, so Explorer, the taskbar,
//! the settings window and Alt+Tab all show the same picture as the tray.
//!
//! A Windows icon is a resource, and resources are compiled by a tool outside
//! Cargo. Rather than take on a build dependency, we write a `.rc`, find the
//! resource compiler that belongs to the toolchain in use, and hand the result
//! to the linker. If no compiler can be found the build still succeeds: the app
//! runs, it just wears the default Windows icon.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// `1 ICON` makes both the `RT_ICON` bits and the `RT_GROUP_ICON` that ties them
/// together, which is what an executable's icon is. The version block is what
/// Explorer's properties sheet shows. Neither needs a header file, so the script
/// compiles with `rc.exe` (MSVC) and with `windres` (GNU) alike.
const SCRIPT: &str = "\
// Generated by crates/app/build.rs - do not edit.
1 ICON \"{icon}\"
1 VERSIONINFO
 FILEVERSION {packed}
 PRODUCTVERSION {packed}
 FILEFLAGSMASK 0x3fL
 FILEFLAGS 0x0L
 FILEOS 0x40004L
 FILETYPE 0x1L
 FILESUBTYPE 0x0L
BEGIN
    BLOCK \"StringFileInfo\"
    BEGIN
        BLOCK \"040904b0\"
        BEGIN
            VALUE \"CompanyName\", \"ShaiWin\"
            VALUE \"FileDescription\", \"ShaiWin - hang your windows on a clothesline\"
            VALUE \"FileVersion\", \"{version}.0\"
            VALUE \"InternalName\", \"shaiwin\"
            VALUE \"LegalCopyright\", \"Copyright (c) 2026 ShaiWin contributors. MIT License with Commons Clause.\"
            VALUE \"OriginalFilename\", \"shaiwin.exe\"
            VALUE \"ProductName\", \"ShaiWin\"
            VALUE \"ProductVersion\", \"{version}.0\"
        END
    END
    BLOCK \"VarFileInfo\"
    BEGIN
        VALUE \"Translation\", 0x409, 1200
    END
END
";

/// One way of turning the `.rc` into an object the linker will take.
type Compiler = fn(&Path, &Path) -> Result<PathBuf, String>;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let Some(icon) = icon_path(&manifest) else {
        println!("cargo:warning=assets/shaiwin.ico is missing; the exe gets no icon");
        return;
    };
    println!("cargo:rerun-if-changed={}", icon.display());

    let version = env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".into());
    let script = SCRIPT
        .replace("{icon}", &quoted_path(&icon))
        .replace("{packed}", &packed_version(&version))
        .replace("{version}", &version);
    let rc_file = out_dir.join("shaiwin.rc");
    if let Err(error) = fs::write(&rc_file, &script) {
        println!("cargo:warning=could not write the resource script: {error}");
        return;
    }

    // Prefer the compiler that matches the toolchain, but take whichever one is
    // actually installed: `rc.exe` needs the Windows SDK and is not on PATH
    // outside a Developer prompt, and `windres` only ships with GNU toolchains.
    // GNU ld refuses the `.res` that `rc.exe` writes, so on a GNU target the
    // MSVC route goes through `cvtres.exe` first and hands over a COFF object.
    let msvc = env::var("CARGO_CFG_TARGET_ENV").map(|env| env == "msvc").unwrap_or(false);
    let attempts: [Compiler; 2] = if msvc {
        [compile_with_rc, compile_with_windres]
    } else {
        [compile_with_windres, compile_with_rc_through_cvtres]
    };
    let mut problems = Vec::new();
    for attempt in attempts {
        match attempt(&rc_file, &out_dir) {
            Ok(artifact) => {
                println!("cargo:rustc-link-arg={}", artifact.display());
                return;
            }
            Err(problem) => problems.push(problem),
        }
    }
    for problem in problems {
        println!("cargo:warning={problem}");
    }
    println!("cargo:warning=no resource compiler found; the exe gets no icon");
}

fn icon_path(manifest: &Path) -> Option<PathBuf> {
    let path = manifest.join("../../assets/shaiwin.ico").canonicalize().ok()?;
    // `canonicalize` gives a verbatim `\\?\` path, which resource compilers do
    // not understand. The drive letter form is what they expect.
    let text = path.display().to_string();
    let plain = text.strip_prefix(r"\\?\").unwrap_or(&text);
    (Path::new(plain).is_file()).then(|| PathBuf::from(plain))
}

/// A path inside a quoted `.rc` string: backslashes doubled, no stray quotes.
fn quoted_path(path: &Path) -> String {
    path.display().to_string().replace('\\', "\\\\").replace('"', "'")
}

/// `1.2.3` becomes `1,2,3,0`; `rc.exe` wants exactly four numbers.
fn packed_version(version: &str) -> String {
    let mut parts: Vec<String> = version
        .split('.')
        .take(3)
        .map(|part| part.chars().take_while(|c| c.is_ascii_digit()).collect::<String>())
        .map(|part| if part.is_empty() { "0".into() } else { part })
        .collect();
    while parts.len() < 4 {
        parts.push("0".into());
    }
    parts.join(",")
}

fn compile_with_rc(rc: &Path, out_dir: &Path) -> Result<PathBuf, String> {
    let compiler = find_rc().ok_or("rc.exe is neither on PATH nor in the Windows SDK")?;
    let artifact = out_dir.join("shaiwin.res");
    run(&compiler, "rc.exe", |cmd| cmd.arg("/nologo").arg("/fo").arg(&artifact).arg(rc))?;
    Ok(artifact)
}

/// The same `rc.exe` output, turned into a COFF object by `cvtres.exe`, which
/// ships with Visual Studio. GNU ld will not link a `.res`, but it links the
/// `.obj` happily, and the resource section ends up in the `.exe` all the same.
fn compile_with_rc_through_cvtres(rc: &Path, out_dir: &Path) -> Result<PathBuf, String> {
    let resource = compile_with_rc(rc, out_dir)?;
    let converter = find_cvtres().ok_or("cvtres.exe is neither on PATH nor in Visual Studio")?;
    let artifact = out_dir.join("shaiwin_res.o");
    let machine = match env::var("CARGO_CFG_TARGET_ARCH").as_deref() {
        Ok("x86_64") => "x64",
        Ok("aarch64") => "arm64",
        Ok("x86") => "x86",
        _ => return Err("cvtres.exe does not know this architecture".into()),
    };
    run(&converter, "cvtres.exe", |cmd| {
        cmd.arg("/nologo")
            .arg(format!("/machine:{machine}"))
            .arg(format!("/out:{}", artifact.display()))
            .arg(&resource)
    })?;
    Ok(artifact)
}

fn compile_with_windres(rc: &Path, out_dir: &Path) -> Result<PathBuf, String> {
    let compiler = which("windres").ok_or("windres is not on PATH")?;
    let artifact = out_dir.join("shaiwin_res.o");
    run(&compiler, "windres", |cmd| {
        cmd.arg("--input").arg(rc).arg("--output-format=coff").arg("--output").arg(&artifact)
    })?;
    Ok(artifact)
}

fn run<F>(compiler: &Path, name: &str, configure: F) -> Result<(), String>
where
    F: FnOnce(&mut Command) -> &mut Command,
{
    let mut command = Command::new(compiler);
    let output = configure(&mut command).output();
    match output {
        Ok(output) if output.status.success() => Ok(()),
        Ok(output) => Err(format!("{name} said: {}", String::from_utf8_lossy(&output.stderr).trim())),
        Err(error) => Err(format!("could not run {name} ({}): {error}", compiler.display())),
    }
}

fn which(name: &str) -> Option<PathBuf> {
    let suffix = if env::consts::OS == "windows" { ".exe" } else { "" };
    env::split_paths(&env::var_os("PATH")?)
        .map(|dir| dir.join(format!("{name}{suffix}")))
        .find(|candidate| candidate.is_file())
}

/// `rc.exe` ships with the Windows SDK, not with the Rust toolchain, so it is
/// usually nowhere on `PATH`. Look through the SDK versions and keep the newest.
fn find_rc() -> Option<PathBuf> {
    if let Some(on_path) = which("rc") {
        return Some(on_path);
    }
    // The SDK keeps its tools at `Windows Kits\10\bin\<version>\<arch>\rc.exe`;
    // per-user SDK installs put the same tree under `LOCALAPPDATA`.
    let mut roots = Vec::new();
    if let Ok(program_files) = env::var("ProgramFiles(x86)").or_else(|_| env::var("PROGRAMFILES")) {
        roots.push(PathBuf::from(program_files).join("Windows Kits").join("10").join("bin"));
    }
    if let Some(local) = env::var_os("LOCALAPPDATA") {
        roots.push(PathBuf::from(local).join("Windows Kits").join("10").join("bin"));
    }
    let mut newest: Option<(u32, PathBuf)> = None;
    for root in roots.iter().filter(|root| root.is_dir()) {
        let Ok(versions) = fs::read_dir(root) else { continue };
        for entry in versions.flatten() {
            let text = entry.file_name().to_string_lossy().to_string();
            let Some(major) = text.split('.').next().and_then(|part| part.parse::<u32>().ok()) else { continue };
            let base = entry.path();
            for candidate in [base.join("x64").join("rc.exe"), base.join("rc.exe")] {
                if candidate.is_file() && newest.as_ref().is_none_or(|(found, _)| major > *found) {
                    newest = Some((major, candidate));
                }
            }
        }
    }
    newest.map(|(_, path)| path)
}

/// `cvtres.exe` lives inside a Visual Studio installation rather than the
/// Windows SDK. Look through the editions and MSVC toolset versions and keep
/// the newest one.
fn find_cvtres() -> Option<PathBuf> {
    if let Some(on_path) = which("cvtres") {
        return Some(on_path);
    }
    let mut newest: Option<(Vec<u32>, PathBuf)> = None;
    for root in [env::var("ProgramFiles(x86)").ok(), env::var("ProgramFiles").ok()].into_iter().flatten() {
        let studio = PathBuf::from(root).join("Microsoft Visual Studio");
        let Ok(editions) = fs::read_dir(&studio) else { continue };
        for edition in editions.flatten() {
            let Ok(products) = fs::read_dir(edition.path()) else { continue };
            for product in products.flatten() {
                let tools = product.path().join("VC").join("Tools").join("MSVC");
                let Ok(versions) = fs::read_dir(&tools) else { continue };
                for version in versions.flatten() {
                    let candidate = version.path().join("bin").join("Hostx64").join("x64").join("cvtres.exe");
                    if !candidate.is_file() {
                        continue;
                    }
                    let rank = version
                        .file_name()
                        .to_string_lossy()
                        .split('.')
                        .map(|part| part.parse::<u32>().unwrap_or(0))
                        .collect::<Vec<u32>>();
                    if newest.as_ref().is_none_or(|(found, _)| rank > *found) {
                        newest = Some((rank, candidate));
                    }
                }
            }
        }
    }
    newest.map(|(_, path)| path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn versions_pack_into_four_numbers() {
        assert_eq!(packed_version("1.2.3"), "1,2,3,0");
        assert_eq!(packed_version("0.1.1"), "0,1,1,0");
        assert_eq!(packed_version("2"), "2,0,0,0");
        assert_eq!(packed_version("1.2.3-beta"), "1,2,3,0");
    }

    #[test]
    fn paths_are_escaped_for_a_quoted_string() {
        let quoted = quoted_path(Path::new(r"C:\Users\me\shai win.ico"));
        assert_eq!(quoted, r"C:\\Users\\me\\shai win.ico");
    }

    #[test]
    fn the_script_names_the_icon_and_the_version() {
        let script = SCRIPT.replace("{icon}", "C:\\a.ico").replace("{packed}", "1,0,0,0").replace("{version}", "1.0.0");
        assert!(script.contains("1 ICON \"C:\\a.ico\""));
        assert!(script.contains("FILEVERSION 1,0,0,0"));
        assert!(!script.contains('{'));
    }
}
